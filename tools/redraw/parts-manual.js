const pin = (name, at, textAt) => ({ type: 'pin', name, at, vertical: true, textAt });
const frame = box => ({ type: 'frame', box });
const sym = (kind, box, dir) => (dir ? { type: 'symbol', kind, box, dir } : { type: 'symbol', kind, box });
const conn = (label, box) => ({ type: 'connector', label, box });
const text = (t, at, size = 18, extra = {}) => ({ type: 'text', text: t, at, size, ...extra });
const wireLabel = (t, at) => text(t, at, 21, { bold: true }); // 元件框內的線色文字（同導線上的線色文字樣式）
// 照原圖近似的基本圖形（js/basemap.js 的 SHAPES）
const L = (...pts) => ({ type: 'line', pts });
const R = (box, extra = {}) => ({ type: 'rect', box, ...extra });
const C = (c, r, extra = {}) => ({ type: 'circle', c, r, ...extra });
const E = (c, rx, ry, a0, a1) => ({ type: 'ellipse', c, rx, ry, a0, a1 });
const loops = (from, to, n, h, side) => (side ? { type: 'loops', from, to, n, h, side } : { type: 'loops', from, to, n, h });
// 燈泡（方向燈）：燈泡圓、燈座矩形、從燈座拉進燈泡的兩條引線、直立的燈絲（兩個環圈，朝燈泡內側）
//   coil: [x, y0, y1] 燈絲位置；side 1 = 燈座在右（環圈朝右），−1 = 燈座在左；tab：燈座外側的小接座
// 儀錶組的小燈：燈泡圓（燈座外那段）＋燈座矩形，y 是燈泡頂
const meterLamp = y => [{ ...E([638, y + 24], 24, 24, 34, 326) }, R([658, y + 12, 705, y + 36])]; // 燈座右緣 705：導線從燈座上下兩角接出
// 油錶：圓＋內部直立小線圈＋指針；轉速錶：外圈、刻度圈、刻度、中心與指針、x1000／rpm 字樣
const fuelGauge = [C([638, 636], 51), loops([650, 598], [650, 668], 6, 10, -1), L([608, 660], [642, 633])]; // 圓右緣 x≈689，Y/W、B 線從這裡接出
